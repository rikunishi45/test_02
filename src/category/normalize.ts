/**
 * 摘要を照合用に正規化する。
 *
 * カード明細の摘要は表記が揺れる。実データ（楽天カード）で確認した形：
 *
 * - 全角英数：`ＶＩＳＡ海外利用` `楽天ＳＰ` `ＢＩＧＬＯＢＥ利用料`
 * - 半角カナ：`ｱﾏｿﾞﾝﾌﾟﾗｲﾑｶｲﾋ` `ﾈｯﾄﾌﾘｯｸｽ`（濁点が分離している）
 * - 全角ハイフン U+FF0D：`セブン－イレブン`
 * - 区切りが U+3000（全角空白）で、後ろに半角空白が続く
 *
 * NFKC がこの4つすべてを畳む（実測で確認）。半角カナの濁点も合成される。
 * 自前で文字表を持たない理由はここにある——表を持てば必ず抜けが出る。
 *
 * **NFKC が直さないもの：** カード会社が小書き文字を大書きで転記した形
 * （`ﾏﾂｸｽﾊﾞﾘﾕ` → `マツクスバリユ`。実名の「マックスバリュ」にはならない）。
 * ルールは実名ではなく、この正規化後の形に合わせて書く必要がある。
 */
export function normalizeDescription(description: string): string {
  return description.normalize("NFKC").replace(/\s+/gu, " ").trim();
}
