import { describe, it, expect } from "vitest";
import { parseDate } from "./parse-date.js";

describe("parseDate", () => {
  describe("受け付ける形式", () => {
    it("スラッシュ区切りでゼロ埋め済みのとき、YYYY-MM-DD を返す", () => {
      expect(parseDate("2026/08/03")).toBe("2026-08-03");
    });

    it("ハイフン区切りでゼロ埋め済みのとき、そのまま YYYY-MM-DD を返す", () => {
      expect(parseDate("2026-08-03")).toBe("2026-08-03");
    });

    it("スラッシュ区切りでゼロ埋めが無いとき、月日をゼロ埋めして返す", () => {
      expect(parseDate("2026/8/3")).toBe("2026-08-03");
    });

    it("月だけゼロ埋めが無いとき、月をゼロ埋めして返す", () => {
      expect(parseDate("2026/8/13")).toBe("2026-08-13");
    });

    it("日だけゼロ埋めが無いとき、日をゼロ埋めして返す", () => {
      expect(parseDate("2026/12/3")).toBe("2026-12-03");
    });

    it("年月日形式のとき、YYYY-MM-DD を返す", () => {
      expect(parseDate("2026年8月3日")).toBe("2026-08-03");
    });

    it("年月日形式で2桁の月日のとき、YYYY-MM-DD を返す", () => {
      expect(parseDate("2026年12月25日")).toBe("2026-12-25");
    });
  });

  describe("前後の空白", () => {
    it("前後に空白があるとき、除去して正規化する", () => {
      expect(parseDate("  2026-08-03  ")).toBe("2026-08-03");
    });

    it("前後にタブや改行があるとき、除去して正規化する", () => {
      expect(parseDate("\t2026/8/3\n")).toBe("2026-08-03");
    });
  });

  describe("月の境界", () => {
    it("月が 01 のとき（下限のすぐ内側）、成功する", () => {
      expect(parseDate("2026-01-15")).toBe("2026-01-15");
    });

    it("月が 12 のとき（上限のすぐ内側）、成功する", () => {
      expect(parseDate("2026-12-15")).toBe("2026-12-15");
    });

    it("月が 00 のとき（下限のすぐ外側）、例外を送出する", () => {
      expect(() => parseDate("2026-00-01")).toThrow();
    });

    it("月が 13 のとき（上限のすぐ外側）、例外を送出する", () => {
      expect(() => parseDate("2026-13-01")).toThrow();
    });

    it("月が 99 のとき、例外を送出する", () => {
      expect(() => parseDate("2026-99-01")).toThrow();
    });
  });

  describe("日の境界", () => {
    it("日が 01 のとき（下限のすぐ内側）、成功する", () => {
      expect(parseDate("2026-08-01")).toBe("2026-08-01");
    });

    it("日が 00 のとき（下限のすぐ外側）、例外を送出する", () => {
      expect(() => parseDate("2026-01-00")).toThrow();
    });

    it("31日ある月の31日は成功する", () => {
      expect(parseDate("2026-01-31")).toBe("2026-01-31");
    });

    it("31日ある月の32日は例外を送出する", () => {
      expect(() => parseDate("2026-01-32")).toThrow();
    });

    it("12月31日は成功する", () => {
      expect(parseDate("2026-12-31")).toBe("2026-12-31");
    });

    it("12月32日は例外を送出する", () => {
      expect(() => parseDate("2026-12-32")).toThrow();
    });

    it("30日までの月（4月）の30日は成功する", () => {
      expect(parseDate("2026-04-30")).toBe("2026-04-30");
    });

    it("30日までの月（4月）の31日は例外を送出する", () => {
      expect(() => parseDate("2026-04-31")).toThrow();
    });

    it("30日までの月（11月）の30日は成功する", () => {
      expect(parseDate("2026-11-30")).toBe("2026-11-30");
    });

    it("30日までの月（11月）の31日は例外を送出する", () => {
      expect(() => parseDate("2026-11-31")).toThrow();
    });

    it("2月30日は例外を送出する", () => {
      expect(() => parseDate("2026-02-30")).toThrow();
    });
  });

  describe("うるう年", () => {
    it("平年の2月28日は成功する（境界のすぐ内側）", () => {
      expect(parseDate("2026-02-28")).toBe("2026-02-28");
    });

    it("平年の2月29日は例外を送出する（境界のすぐ外側）", () => {
      expect(() => parseDate("2026-02-29")).toThrow();
    });

    it("4で割り切れる年の2月29日は成功する", () => {
      expect(parseDate("2024-02-29")).toBe("2024-02-29");
    });

    it("4で割り切れる年でも2月30日は例外を送出する", () => {
      expect(() => parseDate("2024-02-30")).toThrow();
    });

    it("100で割り切れて400で割り切れない年の2月29日は例外を送出する", () => {
      expect(() => parseDate("1900-02-29")).toThrow();
    });

    it("100で割り切れて400で割り切れない年（2100年）の2月29日は例外を送出する", () => {
      expect(() => parseDate("2100-02-29")).toThrow();
    });

    it("100で割り切れて400で割り切れない年でも2月28日は成功する", () => {
      expect(parseDate("1900-02-28")).toBe("1900-02-28");
    });

    it("400で割り切れる年の2月29日は成功する", () => {
      expect(parseDate("2000-02-29")).toBe("2000-02-29");
    });

    it("うるう年判定はスラッシュ区切りでも同じく効く", () => {
      expect(parseDate("2024/2/29")).toBe("2024-02-29");
      expect(() => parseDate("2026/2/29")).toThrow();
    });

    it("うるう年判定は年月日形式でも同じく効く", () => {
      expect(parseDate("2024年2月29日")).toBe("2024-02-29");
      expect(() => parseDate("2026年2月29日")).toThrow();
    });
  });

  describe("2桁の年", () => {
    it("年が2桁のとき（曖昧なため）、例外を送出する", () => {
      expect(() => parseDate("26/08/03")).toThrow();
    });

    it("年が2桁でハイフン区切りのとき、例外を送出する", () => {
      expect(() => parseDate("26-08-03")).toThrow();
    });

    it("年が4桁なら同じ日付が成功する（2桁ケースとの対）", () => {
      expect(parseDate("2026/08/03")).toBe("2026-08-03");
    });

    it("年が3桁のとき、例外を送出する", () => {
      expect(() => parseDate("226-08-03")).toThrow();
    });

    it("年が5桁のとき、例外を送出する", () => {
      expect(() => parseDate("12026-08-03")).toThrow();
    });
  });

  describe("形式として認められない入力", () => {
    it("空文字列のとき、例外を送出する", () => {
      expect(() => parseDate("")).toThrow();
    });

    it("空白のみのとき、例外を送出する", () => {
      expect(() => parseDate("   ")).toThrow();
    });

    it("日付でない文字列のとき、例外を送出する", () => {
      expect(() => parseDate("abc")).toThrow();
    });

    it("年月しか無いとき、例外を送出する", () => {
      expect(() => parseDate("2026-08")).toThrow();
    });

    it("年しか無いとき、例外を送出する", () => {
      expect(() => parseDate("2026")).toThrow();
    });

    it("スラッシュ区切りの日付の前に余分な文字があるとき、例外を送出する", () => {
      expect(() => parseDate("約2026/08/03")).toThrow();
    });

    it("年月日形式の日付の前に余分な文字があるとき、例外を送出する", () => {
      expect(() => parseDate("約2026年8月3日")).toThrow();
    });

    it("年月日形式の日付の後ろに余分な文字があるとき、例外を送出する", () => {
      expect(() => parseDate("2026年8月3日ごろ")).toThrow();
    });

    it("区切りが無い8桁の数字のとき、例外を送出する", () => {
      expect(() => parseDate("20260803")).toThrow();
    });

    it("ドット区切りのとき、例外を送出する", () => {
      expect(() => parseDate("2026.08.03")).toThrow();
    });

    it("区切りが混在するとき、例外を送出する", () => {
      expect(() => parseDate("2026/08-03")).toThrow();
    });

    it("月日年の順のとき、例外を送出する", () => {
      expect(() => parseDate("08/03/2026")).toThrow();
    });

    it("要素が4つあるとき、例外を送出する", () => {
      expect(() => parseDate("2026/08/03/04")).toThrow();
    });

    it("日付の後ろに時刻が続くとき、例外を送出する", () => {
      expect(() => parseDate("2026-08-03T00:00:00")).toThrow();
    });

    it("月が数字でないとき、例外を送出する", () => {
      expect(() => parseDate("2026-aa-03")).toThrow();
    });

    it("年月日形式で 日 が欠けているとき、例外を送出する", () => {
      expect(() => parseDate("2026年8月3")).toThrow();
    });
  });

  describe("戻り値の形式", () => {
    it("どの入力形式でも、戻り値は10文字の YYYY-MM-DD である", () => {
      expect(parseDate("2026/8/3")).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      expect(parseDate("2026年8月3日")).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      expect(parseDate("2026-08-03")).toMatch(/^\d{4}-\d{2}-\d{2}$/);
    });
  });
});
